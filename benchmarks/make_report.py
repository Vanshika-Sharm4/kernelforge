"""Generate docs/RESULTS.md from measured CSVs (never hand-edit the numbers).

    python -m benchmarks.make_report --tag colab-t4
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import pandas as pd


def speedup_table(df: pd.DataFrame, kernel: str, metric: str, base: str, new: str, unit: str) -> str:
    d = df[df.kernel == kernel]
    if d.empty:
        return "_not measured_\n"
    lines = [f"| case | {base} ({unit}) | {new} ({unit}) | speedup |", "|---|---:|---:|---:|"]
    for label in dict.fromkeys(d.label):
        a = d[(d.label == label) & (d.variant == base)][metric].mean()
        b = d[(d.label == label) & (d.variant == new)][metric].mean()
        if pd.notna(a) and pd.notna(b) and a > 0:
            lines.append(f"| {label} | {a:.1f} | {b:.1f} | {b / a:.2f}x |")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--tag", required=True)
    args = parser.parse_args()
    root = Path("results") / args.tag
    env = json.loads((root / "env.json").read_text())

    parts = [
        "# Results\n",
        "> Auto-generated by `python -m benchmarks.make_report`. All numbers are measured, not estimated.\n",
        "## Environment\n",
        "\n".join(f"- **{k}**: {v}" for k, v in env.items() if v) + "\n",
    ]

    kernels = pd.read_csv(root / "kernels.csv")
    dtype = kernels.dtype.iloc[0]
    parts += [
        f"## Kernel micro-benchmarks ({dtype})\n",
        "Speedup > 1 means the Triton kernel is faster than the PyTorch baseline.\n",
        "### Row softmax (GB/s)\n", speedup_table(kernels, "softmax", "gbps", "torch", "triton", "GB/s"),
        "### Fused scale + causal mask + softmax (effective GB/s)\n",
        speedup_table(kernels, "causal_softmax", "gbps", "torch", "triton", "GB/s"),
        "### LayerNorm (GB/s)\n", speedup_table(kernels, "layernorm", "gbps", "torch", "triton", "GB/s"),
        "### Matmul vs cuBLAS (TFLOPS)\n", speedup_table(kernels, "matmul", "tflops", "torch", "triton", "TFLOPS"),
        "### Fused matmul + bias + GELU vs eager (TFLOPS)\n",
        speedup_table(kernels, "matmul_bias_gelu", "tflops", "torch", "triton", "TFLOPS"),
        "### int8 weights vs fp16 weights, Triton kernels (effective GB/s)\n",
        speedup_table(kernels, "matmul_w8", "gbps", "triton-fp16-weights", "triton-int8-weights", "GB/s"),
        "Plots: see the PNG files next to the CSVs in `results/" + args.tag + "/`.\n",
    ]

    model_csv = root / "model.csv"
    if model_csv.exists():
        m = pd.read_csv(model_csv)
        parts.append("## End-to-end GPT-2 (124M), fp16\n")
        parts.append(f"Prompt length {m.prompt_len.iloc[0]}, {m.new_tokens.iloc[0]} new tokens, greedy decoding.\n")
        cols = ["backend", "int8", "kv_cache", "batch", "prefill_ms", "decode_ms_per_token",
                "decode_tokens_per_s", "weight_bw_gbps", "peak_mem_gb"]
        header = "| " + " | ".join(cols) + " |\n|" + "---|" * len(cols) + "\n"
        body = "".join("| " + " | ".join(str(v) for v in row) + " |\n" for row in m[cols].itertuples(index=False))
        parts.append(header + body)
        parts.append("`weight_bw_gbps` = model bytes / decode step time: how much of the GPU's memory "
                     "bandwidth the decode step uses just streaming weights.\n")

    Path("docs").mkdir(exist_ok=True)
    Path("docs/RESULTS.md").write_text("\n".join(parts))
    print("wrote docs/RESULTS.md")


if __name__ == "__main__":
    main()
